// Мост реактивности между складом постеров и экранами. Сам склад про Vue не знает: он общий с веткой script.
// Здесь его сигнал «появился постер» становится счётчиком, на который подписаны сборщики строк.

import { ref } from 'vue'

import { onCoversChanged } from '@/core/posters'

/** Растёт при появлении постеров. Читают сборщики строк — ради перерисовки плиток. */
export const coversStamp = ref(0)

// Подписка на весь срок жизни окна: модуль живёт столько же, сколько приложение, отписка не нужна.
onCoversChanged(() => {
  coversStamp.value += 1
})

/**
 * Зависимость сборщика строк от склада постеров. Ставится рядом с peekLook: без неё строка, собранная до появления картинки, останется с адресом CDN и не перерисуется сама.
 */
export function watchCovers(): void {
  void coversStamp.value
}
