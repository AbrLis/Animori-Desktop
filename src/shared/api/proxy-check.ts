// Живой запрос через прокси — то, чего не может TCP-щуп в src-tauri/src/proxy.rs.
//
// Щуп открывает соединение с адресом прокси и на этом заканчивается: прокси,
// который принимает соединение, но наружу не пускает, для него неотличим
// от рабочего. Отсюда второй шаг — настоящий запрос к известному адресу.
// Он идёт тем же каналом, что и остальная работа программы (Bridge.http),
// поэтому исход говорит о канале, а не о щупе.
//
// В учёт состояния сети (core/net-health.ts) исход не отдаётся намеренно:
// там считаются отказы ИСТОЧНИКОВ, а здесь проверяется настройка, из-за
// которой запрос мог не уйти вовсе. Одна и та же неудача попала бы в сводку
// дважды — и как отказ GitHub, и как отказ прокси.
//
// Слот берётся у общего ограничителя GitHub: инвариант 1 не делает исключений
// для проверок по кнопке.

import { Bridge } from '@/bridge'

import { Logger } from '../utils/logger'
import { githubLimiter } from './rate-limit'

/**
 * Что читаем. Файл выпуска на GitHub: адрес уже разрешён в capabilities,
 * отдаётся без входа, лежит в репозитории и потому заведомо не пуст.
 */
const CHECK_URL =
  'https://raw.githubusercontent.com/foulnike/Animori-Desktop/main/README.md'

/** Потолок ожидания: проверка идёт по кнопке, и ждать дольше нечего. */
const CHECK_TIMEOUT_MS = 8000

/**
 * Прошёл ли запрос. Вид сбоя не возвращается: о том, что прокси молчит,
 * скажет щуп, а здесь нужен ровно один ответ — ушёл запрос или нет.
 */
export async function proxyLiveCheck(): Promise<boolean> {
  await githubLimiter.acquireSlot()

  try {
    const res = await Bridge.http.request({
      method: 'GET',
      url: CHECK_URL,
      credentials: 'omit',
      timeoutMs: CHECK_TIMEOUT_MS,
    })

    return res.ok
  } catch (e) {
    // Отказ — это исход проверки, а не поломка: о нём и говорит false.
    // В журнал всё же пишем: молчаливый catch запрещён инвариантом 2.
    Logger('WARN', 'Прокси: проверочный запрос не прошёл', e)
    return false
  }
}
