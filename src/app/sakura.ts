// Геометрия сакуры знака приложения: лепесток, пять поворотов и два
// разворота — для подложки кнопки (sakuraTurn) и для метки рядом с
// текстом (sakuraTurnMark).
//
// Живёт отдельно, а не внутри самих компонентов, потому что у знака
// два контекста употребления и два разворота лепестка: плотный для
// подложки, узкий для метки. Две копии пути разошлись бы при первой
// правке, а расхождение в форме лепестка — это расхождение в самом
// знаке программы.
//
// Откуда числа — в шапке SakuraBloom.vue, здесь только суть: путь взят
// из AppMark.vue символ в символ. Полуширина 0.7038 — вариант кнопки,
// соседние лепестки сходятся ровно в точку без захлёста; на 28 пикселях
// прорезь между ними — один пиксель, и впадина там читается за счёт
// контраста розового с тёмно-синим. Полуширина 0.52 — вариант метки
// рядом с текстом; прорези глубже, и сакура узнаётся с 12 пикселей,
// когда у варианта кнопки тот же размер сходит на круглое пятно.

/** Лепесток знака: остриём вверх, надрез в точке (16, 7). */
export const SAKURA_PETAL =
  'M16 17.1 C12.1 16.6 9.3 13.2 9.6 9.8 C9.8 6.5 12.9 4.5 16 7 ' +
  'C19.1 4.5 22.2 6.5 22.4 9.8 C22.7 13.2 19.9 16.6 16 17.1 Z'

/** Пять поворотов по 72 градуса — ровно как в маске знака. */
export const SAKURA_TURNS: ReadonlyArray<number> = [0, 72, 144, 216, 288]

// 1.7467 выводит наибольший радиус лепестка на 18 единиц в квадрате 32 —
// одинаково для обоих вариантов: радиус — это размер знака, и его трогать
// незачем. 1.2291/0.9075 — сжатие поперёк оси лепестка: 1.2291 даёт 0.7038
// полуширины и сходится ровно в точку с соседом (вариант кнопки, где
// нужен плотный круг-силуэт), 0.9075 даёт 0.52 полуширины и прорези
// между лепестками (вариант метки рядом с текстом, где нужно узнавание).
// оба translate нужны, чтобы scale шёл от центра квадрата, а не от его
// левого верхнего угла.
export function sakuraTurn(turn: number): string {
  return `rotate(${turn} 16 16) translate(16 16) scale(1.2291 1.7467) translate(-16 -16)`
}

/**
 * Разворот лепестка для метки рядом с текстом.
 *
 * ПОЧЕМУ ДРУГОЕ СЖАТИЕ
 *
 * Знак кнопки проектировался под 28 пикселей и подложку: в покое он круг,
 * под курсором лепестки раскрываются и между ними видны узкие прорези.
 * Метке такие прорези не нужны — она стоит отдельно, не раскрывается и не
 * дышит, и читать её надо сразу. На пятнадцати пикселях лепестки знака
 * кнопки (полуширина 0.7038) сходятся в точку почти без просвета:
 * прорезь там меньше пикселя, и розовое пятно читается кругом. Узкие
 * лепестки с просветами (полуширина 0.52) на том же размере дают
 * однозначную пятёрку лепестков с прорезями до самого низа — на брау-
 * зерном браке 0.52 видно как сакуру уже с 12 пикселей, а 0.7038 только
 * с 26.
 *
 * Это *тот же* знак: лепесток один, поворотов пять, радиус тот же.
 * Меняется только плотность — как у буквы, у которой в заголовке другой
 * кегль, а в тексте свой.
 */
export function sakuraTurnMark(turn: number): string {
  return `rotate(${turn} 16 16) translate(16 16) scale(0.9075 1.7467) translate(-16 -16)`
}
