// Колонки сетки и «целое число строк». Норму показа мы считаем под десктоп, и это видно прямо
// в комментариях к числам: студия добирает 27 «три полных ряда», лента 36 «четыре по девять»,
// авторы 8 «четыре колонки». На приставке колонок меньше, и последний ряд обрывался посреди
// экрана: 27 при пяти колонках дают пустую шестую строку, 36 — ленту с одной плиткой в последней,
// 8 авторов — ряд, где девятый слот стоит пустым.
//
// Правило одно и общее для всех трёх: сколько ни просили, добираем до целого числа рядов.

/** Сколько колонок сетка расставила по факту. Читается готовая раскладка, а не делим ширину на
 *  плитку: `auto-fill` сам решает, сколько мест влезло, и переизобретать его формулу — верный
 *  способ разойтись с CSS. `0` — сетки в разметке ещё не было, тогда колонки неизвестны. */
export function gridCols(grid: HTMLElement | null): number {
  if (grid === null) return 0

  const track = getComputedStyle(grid).gridTemplateColumns.trim()
  if (track === '' || track === 'none') return 0

  const cols = track.split(/\s+/).length
  // Одна колонка — это и есть ряд: подгонять нечего, и по сути это «колонок не измерили».
  return cols > 1 ? cols : 0
}

/** Наименьшее число, не меньше `want` и кратное количеству колонок: сетка кончается целым рядом.
 *  Колонки неизвестны (`0`) или сетка одноколоночная — возвращаем `want` как есть, то есть
 *  прежнее поведение, пока измерить нечего. */
export function wholeRows(want: number, cols: number): number {
  if (cols < 2) return want
  return Math.ceil(want / cols) * cols
}

/** Наибольшее число, не больше `want` и кратное количеству колонок: недобранный ряд не показываем
 *  вовсе, а оставляем следующей порции.
 *
 *  Обратная сторона `wholeRows`, и она нужна там, где добрать нечем: студия приносит столько
 *  постеров, сколько отдал источник (отбор 18+ вырезает часть выдачи, а лимит страниц мешает
 *  дотянуть), и требование «добить ряд вверх» превращалось в вечный недобор. Здесь вместо этого
 *  отказ от лишней строки: пять рядов по пять лучше, чем четыре полных и два в обрезанном. */
export function wholeRowsDown(want: number, cols: number): number {
  if (cols < 2) return want

  const rows = Math.floor(want / cols)
  // Ниже одного ряда опускаться нельзя: пустая витрина хуже неполной строки.
  return rows >= 1 ? rows * cols : want
}
