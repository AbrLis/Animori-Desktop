<script setup lang="ts">
// Малая сакура: тот же лепесток, что расцветает под курсором на кнопках,
// но в роли знака, а не подложки — небольшая отметка рядом с текстом.
//
// ПОЧЕМУ НЕ SakuraBloom
// Тот собран ради перехода «круг → цветок»: лежит абсолютом внутри
// кнопки, ждёт от неё position и :hover и сам по себе в строке не стоит.
// Здесь нужен знак в потоке строки: обычный инлайновый svg, который
// занимает своё место и красится цветом текста рядом.
//
// ПОЧЕМУ БЕЗ СЕРДЦЕВИНЫ
// Круг-бутон в SakuraBloom закрывает пустоту кнопки в покое. Отдельно
// стоящему знаку прятать нечего: впадины между лепестками держат форму
// сами, а круг под ними их только забил бы.
//
// ПОЧЕМУ viewBox С ОТСТУПОМ
// Лепестки доходят до радиуса 18.08 от центра квадрата 32 — две единицы
// наружу. SakuraBloom решает это overflow: visible, но знаку в строке
// выступать за свою клетку нельзя: он отъел бы место у соседа по flex
// невидимым краем. Поэтому кадр расширен до 36.2 единицы и цветок
// целиком в него входит: заданная ширина в пикселях равна видимой.
//
// ГЕОМЕТРИЯ — общая с подложкой, лежит в app/sakura.ts. Лепесток один,
// поворотов пять; меняется только сжатие (sakuraTurnMark против
// sakuraTurn), иначе на 14 пикселях прорези между лепестками пропадают
// и знак сходит на розовое пятно. Почему именно так — в sakura.ts.
import { SAKURA_PETAL, SAKURA_TURNS, sakuraTurnMark } from '../sakura'
</script>

<template>
  <svg class="am-sakura" viewBox="-2.1 -2.1 36.2 36.2" aria-hidden="true" focusable="false">
    <path
      v-for="turn in SAKURA_TURNS"
      :key="turn"
      :d="SAKURA_PETAL"
      :transform="sakuraTurnMark(turn)"
    />
  </svg>
</template>

<!-- Стили без scoped: имя am-sakura короткое, но префикс всё равно свой,
     и правил у знака немного. scoped добавил бы хеш без пользы. -->
<style>
/* Размер задаёт тот, кто ставит знак, через --am-sakura-size. Без
   размера знак растягивается во весь блок, и в строке текста это оборачи-
   вается заглавной буквой из 32 единиц — ровно противоположение метке.
   По умолчанию 1em: знак становится соразмерен кеглю текста рядом. */
.am-sakura {
  display: block;
  flex: none;
  width: var(--am-sakura-size, 1em);
  height: var(--am-sakura-size, 1em);
  fill: currentcolor;
}
</style>
